# ── Stage 6: SSM secrets ─────────────────────────────────────────────────

ssm_version() {
  # prints the parameter version, or nothing if it cannot be read
  aws ssm get-parameter --name "$1" --query Parameter.Version --output text 2>/dev/null || true
}

secret_source_hint() {
  case "$1" in
    POSTGRES_PRISMA_URL) echo "Neon pooled connection string (same value Vercel uses as POSTGRES_PRISMA_URL)" ;;
    IGDB_CLIENT_ID)      echo "Twitch developer console application: Client ID" ;;
    IGDB_CLIENT_SECRET)  echo "Same Twitch application: Client Secret" ;;
    STEAM_API_KEY)       echo "https://steamcommunity.com/dev/apikey" ;;
  esac
}

step_6_ssm_secrets() {
  stage "SSM SecureString secrets"
  say "Terraform created four parameters with a placeholder and ignore_changes on the value."
  say "Real values go in out of band: hidden prompts, passed to the AWS CLI from a 0600 temp file (never on the command line), never saved."
  printf '\n'

  local prefix name param version todo=() todo_values=()
  prefix=$(tf_out "$PROD_DIR" ssm_parameter_prefix)
  for name in "${SSM_SECRET_NAMES[@]}"; do
    param="${prefix}/${name}"
    if (( DRY_RUN )); then
      show_cmd aws ssm get-parameter --name "$param" --query Parameter.Version --output text
      todo+=("$name")
      continue
    fi
    version=$(ssm_version "$param")
    if [[ -z "$version" ]]; then
      die "Parameter $param not found. Did stage 5 apply prod/?"
    elif (( version > 1 )); then
      ok "$name already set (version $version)"
      confirm "Overwrite $name with a new value?" && todo+=("$name")
    else
      note "$name still holds the placeholder (version 1)"
      todo+=("$name")
    fi
  done

  if (( ${#todo[@]} == 0 )); then
    ok "nothing to write"
  else
    printf '\n'
    local value i
    for name in "${todo[@]}"; do
      note "$name: $(secret_source_hint "$name")"
      if (( DRY_RUN )); then
        todo_values+=("<hidden>")
        continue
      fi
      value=""
      while [[ -z "$value" ]]; do
        ask_secret value "Paste $name (hidden):" || die "No input for $name."
        [[ -z "$value" ]] && fail "Empty value."
        if [[ "$name" == "POSTGRES_PRISMA_URL" && ! "$value" =~ ^postgres(ql)?:// ]]; then
          fail "Expected a postgres:// or postgresql:// connection string."
          value=""
        fi
      done
      todo_values+=("$value")
      value=""
    done

    printf '\n'
    say "About to run (values are read from a temp file, not shown):"
    for name in "${todo[@]}"; do
      show_cmd aws ssm put-parameter --name "${prefix}/${name}" --type SecureString --value "file://<temp file>" --overwrite --query Version --output text
    done
    gate "Write ${#todo[@]} SecureString parameter(s) to SSM?"
    if (( ! DRY_RUN )); then
      local secret_file="$TMP_DIR/secret-value" new_version
      for i in "${!todo[@]}"; do
        name="${todo[$i]}"
        ( umask 077; printf '%s' "${todo_values[$i]}" > "$secret_file" )
        new_version=$(aws ssm put-parameter --name "${prefix}/${name}" --type SecureString \
          --value "file://${secret_file}" --overwrite --query Version --output text)
        rm -f "$secret_file"
        ok "$name written (version $new_version)"
      done
    fi
    todo_values=()
  fi

  printf '\n'
  say "Check: every parameter must be above version 1 (values are not printed)."
  local bad=0
  for name in "${SSM_SECRET_NAMES[@]}"; do
    param="${prefix}/${name}"
    if (( DRY_RUN )); then
      show_cmd aws ssm get-parameter --name "$param" --query Parameter.Version --output text
      continue
    fi
    version=$(ssm_version "$param")
    if [[ -n "$version" ]] && (( version > 1 )); then ok "$name version=$version"; else fail "$name version=${version:-unreadable} (placeholder still in place)"; bad=1; fi
  done
  (( bad )) && die "Some parameters still hold the placeholder. Rerun this stage: --from-step 6"
  return 0
}

