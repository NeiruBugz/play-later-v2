abort_clean() {
  printf '\n  %s%s%s\n\n' "$YELLOW" "$1" "$RESET"
  exit 0
}

# soft_fail "msg": fatal in a real run, a warning in a dry run.
soft_fail() {
  if (( DRY_RUN )); then warn "$1 (dry-run: continuing)"; else die "$1"; fi
}

persist() {
  if (( DRY_RUN )); then
    note "[dry-run] would save $1='$2' to $(rel "$ENV_FILE")"
  else
    write_env "$1" "$2"
  fi
}

# On exit: remove temp files; after a failure, say how to resume.
cleanup() {
  local rc=$?
  [[ -n "$TMP_DIR" && -d "$TMP_DIR" ]] && rm -rf "$TMP_DIR"
  if (( rc != 0 && CURRENT_STEP > 0 )); then
    printf '\n  %sStep %s stopped (exit %s). Fix the cause above, then rerun: %s --from-step %s%s\n\n' \
      "$DIM" "$CURRENT_STEP" "$rc" "$(rel "${BASH_SOURCE[0]}")" "$CURRENT_STEP" "$RESET" >&2
  fi
  return "$rc"
}

# input KEY "Prompt" DEFAULT REGEX HINT: a non-secret value. Precedence for the
# suggested value: saved in .bootstrap.env, then environment, then DEFAULT.
# Dry run takes the suggestion without prompting.
input() {
  local key="$1" prompt="$2" default="$3" regex="$4" hint="$5" suggestion value
  suggestion=$(_existing "$key" || true)
  [[ -z "$suggestion" ]] && suggestion="${!key:-}"
  [[ -z "$suggestion" ]] && suggestion="$default"
  if (( DRY_RUN )); then
    value="${suggestion:-<$key>}"
    note "[dry-run] $prompt -> $value"
  else
    while true; do
      read -e -r -p "  ${BOLD}${prompt}${RESET} ${DIM}[${suggestion:-none}]${RESET} " value || die "No input for $key."
      [[ -z "$value" ]] && value="$suggestion"
      if [[ -n "$value" && "$value" =~ $regex ]]; then break; fi
      fail "$hint"
    done
  fi
  persist "$key" "$value"
  printf -v "$key" '%s' "$value"
}

# load_inputs: restore the saved answers for a resumed run.
load_inputs() {
  local key value
  for key in "${INPUT_KEYS[@]}"; do
    value=$(_existing "$key" || true)
    [[ -z "$value" ]] && value="${!key:-}"
    if [[ -z "$value" ]]; then
      if (( DRY_RUN )); then value="<$key>"; else die "$key is not saved yet. Run stage 2 first: $(rel "${BASH_SOURCE[0]}") --from-step 2"; fi
    fi
    printf -v "$key" '%s' "$value"
  done
  export AWS_REGION
}

