# tf_out ROOT_DIR OUTPUT_NAME: terraform output -raw, placeholder in a dry run.
tf_out() {
  if (( DRY_RUN )); then
    show_cmd terraform "-chdir=$(rel "$1")" output -raw "$2" >&2
    printf '<terraform output %s>' "$2"
    return 0
  fi
  terraform "-chdir=$1" output -raw "$2"
}

# render_file PATH CONTENT: write a gitignored file, idempotent. Shows a diff
# and asks before replacing a different existing file.
render_file() {
  local path="$1" content="$2" current=""
  if (( DRY_RUN )); then
    note "[dry-run] would write $(rel "$path"):"
    printf '%s\n' "$content" | sed 's/^/      /'
    return 0
  fi
  if [[ -f "$path" ]]; then
    current=$(cat "$path")
    if [[ "$current" == "$content" ]]; then
      ok "$(rel "$path") already up to date"
      return 0
    fi
    warn "$(rel "$path") exists and differs:"
    local proposed
    proposed=$(mktemp)
    printf '%s\n' "$content" > "$proposed"
    diff "$path" "$proposed" | sed 's/^/      /' || true
    rm -f "$proposed"
    confirm "Overwrite $(rel "$path")?" || abort_clean "Left $(rel "$path") as is. Rerun to resume at step $CURRENT_STEP."
  fi
  printf '%s\n' "$content" > "$path"
  ok "wrote $(rel "$path")"
}

