# ── Stage 1: preflight ───────────────────────────────────────────────────

step_1_preflight() {
  stage "Preflight: tools and logins"
  say "Checks the CLIs and logins the later stages rely on. Nothing is changed."
  say "AWS credentials come from your environment: AWS_PROFILE=${AWS_PROFILE:-<default credential chain>}"
  note "Use an admin profile for the target account (export AWS_PROFILE=... before running this wizard)."
  printf '\n'

  local tool hint missing=0
  for tool in aws terraform gh vercel jq; do
    if command -v "$tool" >/dev/null 2>&1; then
      ok "$tool found ($(command -v "$tool"))"
    else
      case "$tool" in
        aws)       hint="brew install awscli" ;;
        terraform) hint="tfenv install $TF_VERSION && tfenv use $TF_VERSION" ;;
        gh)        hint="brew install gh" ;;
        vercel)    hint="npm i -g vercel" ;;
        jq)        hint="brew install jq" ;;
      esac
      fail "$tool missing. Install: $hint"
      missing=1
    fi
  done
  (( missing )) && soft_fail "Install the missing tools and rerun."

  if command -v terraform >/dev/null 2>&1; then
    local tf_actual
    tf_actual=$(terraform version | sed -n '1s/^Terraform v//p')
    if [[ "$tf_actual" == "$TF_VERSION" ]]; then
      ok "terraform $tf_actual (pinned version)"
    else
      soft_fail "terraform is $tf_actual, the stack pins exactly $TF_VERSION (tfenv install $TF_VERSION && tfenv use $TF_VERSION)."
    fi
  fi
  if command -v aws >/dev/null 2>&1; then
    local aws_major
    aws_major=$(aws --version 2>&1 | sed -n 's|^aws-cli/\([0-9]*\)\..*|\1|p')
    [[ "$aws_major" == "2" ]] && ok "aws CLI v2" || soft_fail "AWS CLI v2 required (found: ${aws_major:-unknown})."
  fi

  printf '\n'
  if (( DRY_RUN )); then
    show_cmd aws sts get-caller-identity
    show_cmd gh auth status
    show_cmd vercel whoami
    ACCOUNT_ID="${ACCOUNT_ID_PRESET:-123456789012}"
  else
    local identity
    identity=$(aws sts get-caller-identity --output json 2>&1) \
      || die "aws sts get-caller-identity failed. Set AWS_PROFILE or run aws sso login. Output: $identity"
    ACCOUNT_ID=$(printf '%s' "$identity" | jq -r .Account)
    ok "AWS account $ACCOUNT_ID as $(printf '%s' "$identity" | jq -r .Arn)"
    gh auth status >/dev/null 2>&1 || die "gh is not authenticated. Run: gh auth login (needs admin on $GH_REPO)."
    ok "gh authenticated"
    local vercel_user
    vercel_user=$(vercel whoami 2>/dev/null) || die "vercel is not logged in. Run: vercel login"
    ok "vercel logged in as $vercel_user"
  fi

  printf '\n'
  warn "Confirm $ACCOUNT_ID is the AWS account you intend to deploy to."
  gate "Continue with this account?"
}

