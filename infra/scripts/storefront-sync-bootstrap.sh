import_if_needed() {
  # import_if_needed DIR ADDRESS ARN: import a pre-existing provider that is not in state yet
  local dir="$1" address="$2" arn="$3"
  [[ -z "$arn" ]] && return 0
  if (( ! DRY_RUN )) && terraform "-chdir=$dir" state list 2>/dev/null | grep -qx "$address"; then
    ok "$address already in state"
    return 0
  fi
  warn "$address exists in AWS but not in state."
  gate "Import it (terraform import $address)?"
  run terraform "-chdir=$dir" import "$address" "$arn"
}

tf_plan_and_apply() {
  # tf_plan_and_apply DIR: plan -out, show, require "yes", apply the saved plan
  local dir="$1" rc=0 shown
  shown=$(rel "$dir")
  run terraform "-chdir=$dir" init -backend-config=backend.hcl

  if [[ "$dir" == "$SHARED_DIR" ]]; then
    import_if_needed "$dir" aws_iam_openid_connect_provider.github "$(oidc_provider_arn "token.actions.githubusercontent.com")"
    import_if_needed "$dir" aws_iam_openid_connect_provider.vercel "$(oidc_provider_arn "oidc.vercel.com/${VERCEL_TEAM_SLUG}")"
  fi

  show_cmd terraform "-chdir=$dir" plan -detailed-exitcode -out=plan.tfplan
  if (( DRY_RUN )); then
    rc=2
  else
    terraform "-chdir=$dir" plan -detailed-exitcode -out=plan.tfplan || rc=$?
  fi
  case "$rc" in
    0) ok "$shown: no changes, already applied"; return 0 ;;
    2) ;;
    *) die "terraform plan failed in $shown (exit $rc)." ;;
  esac

  run terraform "-chdir=$dir" show plan.tfplan
  if (( ! DRY_RUN )); then
    local destroys
    destroys=$(terraform "-chdir=$dir" show -json plan.tfplan | jq '[.resource_changes[]? | select(.change.actions | index("delete"))] | length')
    printf '\n'
    if [[ "$dir" == "$SHARED_DIR" ]]; then
      note "Expect: fresh account '2 to add, 0 to change, 0 to destroy'; after an import 1 to add plus at most an in-place update of the GitHub provider."
      note "If the plan would remove a client_id_list entry another project relies on, STOP and keep those entries in shared/oidc.tf."
    else
      note "Expect creates only: 2 queues + 2 DLQs, 2 Lambdas with roles/policies/log groups/event source mappings, 4 SSM parameters, 2 IAM roles."
      note "Names must be the savepoint-prod-* names from the runbook table."
    fi
    if (( destroys > 0 )); then
      fail "The plan destroys or replaces $destroys resource(s). Read the plan above before answering."
    fi
  fi

  gate_yes "Apply this saved plan in $shown?"
  run terraform "-chdir=$dir" apply plan.tfplan
  (( DRY_RUN )) || rm -f "$dir/plan.tfplan"
  run terraform "-chdir=$dir" output
}

