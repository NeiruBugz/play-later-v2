run_wizard() {
  while (( $# )); do
    case "$1" in
      --dry-run) DRY_RUN=1 ;;
      --from-step)
        [[ $# -ge 2 && "$2" =~ ^[1-9]$ ]] || die "--from-step needs a number between 1 and $TOTAL_STAGES."
        FROM_STEP="$2"; shift ;;
      -h|--help) usage; exit 0 ;;
      *) usage >&2; die "Unknown argument: $1" ;;
    esac
    shift
  done

  TMP_DIR=$(mktemp -d)
  trap cleanup EXIT

  local start=1 last_done reply=''
  if [[ -n "$FROM_STEP" ]]; then
    start="$FROM_STEP"
  else
    last_done=$(_existing LAST_COMPLETED_STEP || true)
    if [[ "$last_done" =~ ^[1-9]$ ]] && (( last_done < TOTAL_STAGES )) && (( ! DRY_RUN )); then
      printf '\n  Stages 1-%s completed on a previous run.\n' "$last_done"
      read -r -p "  Resume at stage $((last_done + 1))? [Y/n] " reply || reply=""
      [[ "$reply" =~ ^[Nn] ]] || start=$((last_done + 1))
    fi
  fi

  local title="Storefront-sync bootstrap (spec 030)"
  (( DRY_RUN )) && title="$title [dry-run]"
  banner "$title"
  (( DRY_RUN )) && warn "Dry run: commands are printed, nothing is executed or written."
  printf '\n'

  if (( start > 2 )); then load_inputs; ensure_account_id; fi

  local n
  for (( n = start; n <= TOTAL_STAGES; n++ )); do
    CURRENT_STEP=$n
    _STAGE_INDEX=$((n - 1))
    case "$n" in
      1) step_1_preflight ;;
      2) step_2_inputs ;;
      3) step_3_state_bucket ;;
      4) step_4_oidc_check ;;
      5) step_5_terraform_apply ;;
      6) step_6_ssm_secrets ;;
      7) step_7_vercel ;;
      8) step_8_github ;;
      9) step_9_summary ;;
    esac
    (( DRY_RUN )) || [[ "$n" == "$TOTAL_STAGES" ]] || write_env LAST_COMPLETED_STEP "$n" >/dev/null
    if (( n < TOTAL_STAGES )); then
      printf '\n'
      pause "Stage $n done. Press Enter for the next stage."
    fi
  done

  (( DRY_RUN )) || write_env LAST_COMPLETED_STEP "$TOTAL_STAGES" >/dev/null
  if (( DRY_RUN )); then
    note "Dry run only: nothing was executed or written."
  else
    printf '\n  %s%s✓ Bootstrap complete%s\n\n' "$BOLD" "$GREEN" "$RESET"
  fi
  return 0
}

