vercel_has_env() {
  # vercel_has_env NAME: true if NAME exists on Production (uses cached listing)
  grep -Eq "^[[:space:]]*$1[[:space:]]" <<<"$VERCEL_ENV_LISTING"
}

vercel_set_production() {
  # vercel_set_production NAME VALUE: add, or replace after confirmation
  local name="$1" value="$2"
  if vercel_has_env "$name"; then
    warn "$name already exists on Production."
    if [[ "$name" == "AWS_REGION" ]]; then
      note "The runbook says leave an existing AWS_REGION alone, but it must equal $value."
      if (( DRY_RUN )) || confirm "Is the existing Production AWS_REGION exactly '$value'?"; then
        ok "AWS_REGION kept"
        return 0
      fi
    else
      gate "Replace $name on Production with the current value?"
    fi
    run vercel env rm "$name" production --yes
  fi
  run_stdin "$value" vercel env add "$name" production
}

