ok()   { printf '  %s✓%s %s\n' "$GREEN" "$RESET" "$1"; }
fail() { printf '  %s✗ %s%s\n' "$YELLOW" "$1" "$RESET"; }

die() {
  printf '\n  %s✗ %s%s\n' "$YELLOW" "$1" "$RESET" >&2
  exit 1
