# ── Stage 3: state bucket and backend.hcl ────────────────────────────────

state_bucket_policy_file() {
  local file="$TMP_DIR/state-bucket-policy.json"
  cat > "$file" <<JSON
{
  "Version": "2012-10-17",
  "Statement": [{
    "Sid": "DenyInsecureTransport",
    "Effect": "Deny",
    "Principal": "*",
    "Action": "s3:*",
    "Resource": ["arn:aws:s3:::${STATE_BUCKET}", "arn:aws:s3:::${STATE_BUCKET}/*"],
    "Condition": {"Bool": {"aws:SecureTransport": "false"}}
  }]
}
JSON
  printf '%s' "$file"
}

apply_bucket_hardening() {
  local policy_file
  policy_file=$(state_bucket_policy_file)
  run aws s3api put-bucket-versioning --bucket "$STATE_BUCKET" \
    --versioning-configuration Status=Enabled
  run aws s3api put-bucket-encryption --bucket "$STATE_BUCKET" \
    --server-side-encryption-configuration \
    '{"Rules":[{"ApplyServerSideEncryptionByDefault":{"SSEAlgorithm":"AES256"},"BucketKeyEnabled":true}]}'
  run aws s3api put-public-access-block --bucket "$STATE_BUCKET" \
    --public-access-block-configuration \
    BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true
  if (( DRY_RUN || PREVIEW )); then
    note "Bucket policy (TLS only), read from $policy_file:"
    sed 's/^/      /' "$policy_file"
  fi
  run aws s3api put-bucket-policy --bucket "$STATE_BUCKET" --policy "file://$policy_file"
}

verify_bucket() {
  local ok_all=1 value
  if (( DRY_RUN )); then
    show_cmd aws s3api get-bucket-versioning --bucket "$STATE_BUCKET" --query Status --output text
    show_cmd aws s3api get-bucket-encryption --bucket "$STATE_BUCKET" --query 'ServerSideEncryptionConfiguration.Rules[0].ApplyServerSideEncryptionByDefault.SSEAlgorithm' --output text
    show_cmd aws s3api get-public-access-block --bucket "$STATE_BUCKET" --query PublicAccessBlockConfiguration --output json
    return 0
  fi
  value=$(aws s3api get-bucket-versioning --bucket "$STATE_BUCKET" --query Status --output text 2>/dev/null || true)
  if [[ "$value" == "Enabled" ]]; then ok "versioning Enabled"; else fail "versioning is '${value:-off}'"; ok_all=0; fi
  value=$(aws s3api get-bucket-encryption --bucket "$STATE_BUCKET" \
    --query 'ServerSideEncryptionConfiguration.Rules[0].ApplyServerSideEncryptionByDefault.SSEAlgorithm' --output text 2>/dev/null || true)
  if [[ "$value" == "AES256" ]]; then ok "encryption AES256"; else fail "encryption is '${value:-none}'"; ok_all=0; fi
  value=$(aws s3api get-public-access-block --bucket "$STATE_BUCKET" \
    --query 'PublicAccessBlockConfiguration.[BlockPublicAcls,IgnorePublicAcls,BlockPublicPolicy,RestrictPublicBuckets]' --output text 2>/dev/null || true)
  if [[ "$value" == $'True\tTrue\tTrue\tTrue' ]]; then ok "public access fully blocked"; else fail "public access block is '${value:-none}'"; ok_all=0; fi
  value=$(aws s3api get-bucket-policy --bucket "$STATE_BUCKET" --query Policy --output text 2>/dev/null || true)
  if [[ "$value" == *DenyInsecureTransport* ]]; then ok "TLS-only policy present"; else fail "TLS-only policy missing"; ok_all=0; fi
  (( ok_all ))
}

step_3_state_bucket() {
  stage "S3 state bucket and backend.hcl"
  say "Terraform cannot create the bucket that holds its own state, so this is done once with the CLI."
  say "Bucket: $STATE_BUCKET in $AWS_REGION (versioned, SSE, private, TLS-only). Locking uses a .tflock object, no DynamoDB."
  printf '\n'

  local exists=0
  if read_cmd aws s3api head-bucket --bucket "$STATE_BUCKET"; then
    exists=1
  elif (( ! DRY_RUN )); then
    case "$REPLY_ERR" in
      *"(403)"*|*Forbidden*) die "Bucket name $STATE_BUCKET exists but is not accessible to this account (taken globally, or wrong profile). Pick another name in stage 2." ;;
      *"(404)"*|*"Not Found"*|*NoSuchBucket*) exists=0 ;;
      *) die "head-bucket failed unexpectedly: $REPLY_ERR" ;;
    esac
  fi

  if (( exists )); then
    ok "bucket $STATE_BUCKET already exists, verifying its settings"
    if ! verify_bucket; then
      warn "Some hardening settings are missing."
      (( DRY_RUN )) || { PREVIEW=1; apply_bucket_hardening; PREVIEW=0; }
      gate "Re-apply versioning, encryption, public-access block and TLS policy? (idempotent)"
      apply_bucket_hardening
      verify_bucket || die "Bucket settings still not as expected."
    fi
  else
    say "Bucket does not exist. Commands to run:"
    local create=(aws s3api create-bucket --bucket "$STATE_BUCKET" --region "$AWS_REGION")
    [[ "$AWS_REGION" != "us-east-1" ]] && create+=(--create-bucket-configuration "LocationConstraint=$AWS_REGION")
    (( DRY_RUN )) || { show_cmd "${create[@]}"; PREVIEW=1; apply_bucket_hardening; PREVIEW=0; }
    gate "Create and harden $STATE_BUCKET now?"
    run "${create[@]}"
    apply_bucket_hardening
    printf '\n'
    verify_bucket || die "Bucket settings not as expected after creation."
  fi

  printf '\n'
  say "Backend config for both roots (gitignored), built from backend.hcl.example:"
  local root content
  for root in shared prod; do
    content=$(sed -e "s|your-state-bucket-name|${STATE_BUCKET}|" -e "s|your-aws-region|${AWS_REGION}|" "$STACK_DIR/$root/backend.hcl.example")
    render_file "$STACK_DIR/$root/backend.hcl" "$content"
  done
  warn "Never delete this bucket while the stack exists: it holds the Terraform state."
}

