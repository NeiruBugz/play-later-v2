# ── Dry-run aware helpers ────────────────────────────────────────────────

# In a real run the library's pause reads Enter; in a dry run nothing blocks.
pause() {
  (( DRY_RUN )) && return 0
  printf '  %s%s%s ' "$DIM" "${1:-Press Enter to continue}" "$RESET"
  read -r _ || true
}

rel() { printf '%s' "${1#"$REPO_ROOT"/}"; }

# show_cmd prints the exact command, shell-quoted.
show_cmd() {
  local tag="$"
  (( DRY_RUN )) && tag="[dry-run] $"
  printf '  %s%s%s %s' "$DIM" "$tag" "$RESET" "$BOLD"
  printf '%q ' "$@"
  printf '%s\n' "$RESET"
}

# run: show the command, execute it unless --dry-run.
run() {
  show_cmd "$@"
  (( DRY_RUN || PREVIEW )) && return 0
  "$@"
}

# run_stdin VALUE cmd...: like run, feeding VALUE (non-secret) to stdin.
run_stdin() {
  local value="$1"; shift
  local tag="$"
  (( DRY_RUN )) && tag="[dry-run] $"
  printf '  %s%s%s %sprintf %%s %q |%s ' "$DIM" "$tag" "$RESET" "$BOLD" "$value" "$RESET"
  printf '%s' "$BOLD"; printf '%q ' "$@"; printf '%s\n' "$RESET"
  (( DRY_RUN )) && return 0
  printf '%s' "$value" | "$@"
}

# read_cmd: read-only command. Captures stdout in REPLY_OUT and stderr in
# REPLY_ERR. In a dry run it prints the command, calls nothing, returns 1.
read_cmd() {
  REPLY_OUT=""; REPLY_ERR=""
  if (( DRY_RUN )); then
    show_cmd "$@" >&2
    return 1
  fi
  local rc=0
  REPLY_OUT=$("$@" 2>"$TMP_DIR/stderr") || rc=$?
  REPLY_ERR=$(cat "$TMP_DIR/stderr")
  return "$rc"
}

# gate "question": explicit y/N before a mutating step. Declining stops the
# wizard cleanly; rerun resumes at the current step.
gate() {
  if (( DRY_RUN )); then
    note "[dry-run] would ask: $1"
    return 0
  fi
  confirm "$1" || abort_clean "Declined. Nothing further was changed. Rerun to resume at step $CURRENT_STEP."
}

# gate_yes "question": stricter gate, the human must type the word yes.
gate_yes() {
  if (( DRY_RUN )); then
    note "[dry-run] would ask: $1 (type yes)"
    return 0
  fi
  local reply=""
  printf '  %s? %s (type yes to continue) %s' "$YELLOW" "$1" "$RESET"
  read -r reply || true
  [[ "$reply" == "yes" ]] || abort_clean "Not confirmed. Nothing further was changed. Rerun to resume at step $CURRENT_STEP."
}

